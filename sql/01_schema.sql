-- ---------------------------------------------------------------------
-- PubMed
-- ---------------------------------------------------------------------
CREATE TABLE publications (
    pmid               bigint PRIMARY KEY,
    pub_year           int NOT NULL,
    title              text NOT NULL,
    abstract           text,
    keywords           text,
    journal            text,
    doi                text,
    language           text,
    publication_types  text[],
    search_year        int,
    is_rct             boolean GENERATED ALWAYS AS ('Randomized Controlled Trial' = ANY (publication_types)) STORED,
    is_review          boolean GENERATED ALWAYS AS ('Systematic Review' = ANY (publication_types) OR 'Meta-Analysis' = ANY (publication_types) OR 'Review' = ANY (publication_types)) STORED,
    is_included        boolean,
    is_help            boolean
);
COMMENT ON TABLE publications IS 'Статьи PubMed 2000–2025 о психическом здоровье и психологической помощи при бедствиях';
COMMENT ON COLUMN publications.is_included IS 'TRUE — статья учитывается в анализе: упомянут конкретный тип бедствия, либо «бедствие» без контекста COVID-19, терактов и войн';
COMMENT ON COLUMN publications.is_help IS 'TRUE — работа о помощи: психологическая первая помощь, психосоциальная поддержка, терапия, службы, программы';

CREATE TABLE publication_mesh (
    pmid             bigint REFERENCES publications ON DELETE CASCADE,
    descriptor_ui    text,
    descriptor_name  text,
    is_major         boolean,
    PRIMARY KEY (pmid, descriptor_ui)
);
COMMENT ON TABLE publication_mesh IS 'Рубрики MeSH статьи (у статей, проиндексированных в MEDLINE). Географические рубрики показывают, где проводилось исследование';

CREATE TABLE publication_affiliations (
    pmid          bigint REFERENCES publications ON DELETE CASCADE,
    author_order  int,
    affiliation   text
);
COMMENT ON TABLE publication_affiliations IS 'Места работы авторов в том виде, как они указаны в PubMed';

-- Результаты классификации (заполняет 03_classify.sql)
CREATE TABLE publication_tags (
    pmid  bigint REFERENCES publications ON DELETE CASCADE,
    tag   text,
    PRIMARY KEY (pmid, tag)
);
COMMENT ON TABLE publication_tags IS 'Метки статьи по правилам classification_rules: типы бедствий, help, исключаемые контексты';

CREATE TABLE publication_countries (
    pmid   bigint REFERENCES publications ON DELETE CASCADE,
    iso3   char(3) REFERENCES countries,
    basis  text CHECK (basis IN ('mesh', 'title', 'abstract')),
    PRIMARY KEY (pmid, iso3)
);
COMMENT ON TABLE publication_countries IS 'О какой стране статья. Приоритет: географические рубрики MeSH (+ страны из названия), иначе название, иначе аннотация';

CREATE TABLE affiliation_countries (
    affiliation  text PRIMARY KEY,
    iso3         char(3) REFERENCES countries
);
COMMENT ON TABLE affiliation_countries IS 'Страна каждой уникальной строки аффилиации (последнее упоминание страны в строке)';

CREATE TABLE publication_author_countries (
    pmid  bigint REFERENCES publications ON DELETE CASCADE,
    iso3  char(3) REFERENCES countries,
    PRIMARY KEY (pmid, iso3)
);
COMMENT ON TABLE publication_author_countries IS 'Страны, где работают авторы статьи';
