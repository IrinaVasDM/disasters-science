-- ---------------------------------------------------------------------
-- Страны (ISO3 как в EM-DAT)
-- ---------------------------------------------------------------------
CREATE TABLE countries (
    iso3          char(3) PRIMARY KEY,
    name_en       text NOT NULL,
    name_ru       text NOT NULL,
    subregion     text,
    subregion_ru  text,
    region        text,
    region_ru     text
);
COMMENT ON TABLE countries IS 'Страны и территории из EM-DAT: ISO3, названия (англ. по стандарту ООН M49 и рус.), регион';

-- Регулярные выражения для поиска стран в текстах статей
CREATE TABLE country_patterns (
    pattern_id  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso3        char(3) NOT NULL REFERENCES countries,
    pattern     text NOT NULL,
    scope       text NOT NULL CHECK (scope IN ('any', 'text', 'mesh', 'affil')),
    kind        text NOT NULL CHECK (kind IN ('name', 'demonym', 'subnational', 'abbrev'))
);
COMMENT ON TABLE country_patterns IS 'Шаблоны (регулярные выражения PostgreSQL, с учётом регистра) для распознавания стран';
COMMENT ON COLUMN country_patterns.scope IS 'any — везде; text — название/аннотация/аффилиации; mesh — только рубрики MeSH; affil — только аффилиации авторов';
COMMENT ON COLUMN country_patterns.kind IS 'name — название; demonym — прилагательное (Japanese); subnational — штат/провинция/город; abbrev — сокращение (USA, UK)';

